"""Renderers: turn the final lists into a Caddy snippet, an nginx include or JSON."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, replace

from . import __version__
from .config import Config
from .presets import AD_CLICK_PARAMS

# A paid-click identifier in the query string: gclid=..., msclkid=...
AD_CLICK_RE = "(^|&)(" + "|".join(AD_CLICK_PARAMS) + ")="

HEADER_LINES = 3  # comment lines that carry the date; ignored by `n-antibot check`


@dataclass(frozen=True)
class Blocklist:
    v4: list[str]
    v6: list[str]
    agents: tuple[str, ...]
    asns: tuple[str, ...]
    generated_on: str
    manual_block: tuple[str, ...] = ()
    manual_allow: tuple[str, ...] = ()
    # Data-center networks whose PAID AD CLICKS are cut (only filled when `[ads] cut = true`).
    ads_v4: tuple[str, ...] = ()
    ads_v6: tuple[str, ...] = ()
    ads_asns: tuple[str, ...] = ()


def _header(c: str, bl: Blocklist, where: str) -> list[str]:
    return [
        f"{c} Generated by n-antibot {__version__} on {bl.generated_on}. Do not edit by hand: regenerate it.",
        f"{c} {where}",
        f"{c} Networks: {', '.join(bl.asns) or 'none'}, {len(bl.v4)} IPv4 and {len(bl.v6)} IPv6 ranges, "
        f"{len(bl.agents)} robots.",
    ]


def caddy(bl: Blocklist, cfg: Config) -> str:
    """Snippet to `import` as the FIRST line inside a site block.

    Caddy sorts directives: `rewrite` runs before every `handle`, and a `handle` with an exact path wins over
    `handle /prefix/*` and the catch-all `handle`. A named matcher inside `handle @x` would be sorted AFTER path
    handles, so the block would not reach every route. Hence: rewrite to a private path, then abort there.
    """
    p, dest = cfg.caddy_prefix, cfg.caddy_block_path
    excl = " ".join(cfg.exclude_paths)
    lines = _header("#", bl, "Import it as the first line of your site block: import /etc/caddy/n-antibot.caddy")
    ranges = bl.v4 + bl.v6
    if ranges:
        lines.append(f"@{p}Net {{")
        if excl:
            lines.append(f"\tnot path {excl}")
        for i in range(0, len(ranges), 8):
            lines.append(f"\t{cfg.caddy_ip_matcher} " + " ".join(ranges[i : i + 8]))
        lines.append("}")
    if bl.agents:
        lines.append(f"@{p}Agent {{")
        if excl:
            lines.append(f"\tnot path {excl}")
        lines.append(f'\theader_regexp {p}Ua User-Agent "(?i){_alt(bl.agents)}"')
        lines.append("}")
    ads = [*bl.ads_v4, *bl.ads_v6]
    if ads:
        # Data-center networks are only cut when the request is a paid ad click (it carries a click identifier).
        lines.append(f"@{p}AdClick {{")
        if excl:
            lines.append(f"\tnot path {excl}")
        lines.append(f"\texpression {{http.request.uri.query}}.matches('{AD_CLICK_RE}')")
        for i in range(0, len(ads), 8):
            lines.append(f"\t{cfg.caddy_ip_matcher} " + " ".join(ads[i : i + 8]))
        lines.append("}")
    if ranges:
        lines.append(f"rewrite @{p}Net {dest}")
    if bl.agents:
        lines.append(f"rewrite @{p}Agent {dest}")
    if ads:
        lines.append(f"rewrite @{p}AdClick {dest}")
    lines += [f"handle {dest} {{", "\tabort", "}", ""]
    return "\n".join(lines)


def _nginx_path(p: str) -> str:
    if p.startswith("*."):
        return f"~\\.{re.escape(p[2:])}$"
    if p.endswith("*"):
        return "~^" + re.escape(p[:-1])
    return p  # exact match


def nginx(bl: Blocklist, cfg: Config) -> str:
    """Include for the `http {}` context. It defines $<prefix>_block; add `if ($<prefix>_block) { return 444; }`
    to each server. 444 is nginx's "close the connection without answering", the same as Caddy's abort."""
    p = cfg.nginx_prefix
    lines = _header("#", bl, f"include it inside http {{ }} and add to each server: if (${p}_block) {{ return 444; }}")
    lines += [f"geo ${p}_net {{", "\tdefault 0;"]
    lines += [f"\t{r} 1;" for r in bl.v4 + bl.v6]
    lines += ["}", f"map $http_user_agent ${p}_agent {{", "\tdefault 0;"]
    if bl.agents:
        lines.append(f'\t"~*{_alt(bl.agents)}" 1;')
    lines += ["}", f"map $uri ${p}_excluded {{", "\tdefault 0;"]
    lines += [f'\t"{_nginx_path(x)}" 1;' for x in cfg.exclude_paths]
    ads = [*bl.ads_v4, *bl.ads_v6]
    if not ads:
        lines += [
            "}",
            f'map "${p}_net${p}_agent${p}_excluded" ${p}_block {{',
            "\tdefault 0;",
            '\t"100" 1;',
            '\t"010" 1;',
            '\t"110" 1;',
            "}",
            "",
        ]
        return "\n".join(lines)
    # Data-center networks are only cut when the request is a paid ad click (it carries a click identifier).
    lines += ["}", f"geo ${p}_adnet {{", "\tdefault 0;"]
    lines += [f"\t{r} 1;" for r in ads]
    lines += [
        "}",
        f"map $args ${p}_adclick {{",
        "\tdefault 0;",
        f'\t"~{AD_CLICK_RE}" 1;',
        "}",
        f'map "${p}_net${p}_agent${p}_excluded${p}_adnet${p}_adclick" ${p}_block {{',
        "\tdefault 0;",
        '\t"~^1.0" 1;',
        '\t"~^.10" 1;',
        '\t"~^..011$" 1;',
        "}",
        "",
    ]
    return "\n".join(lines)


def _regex_path(p: str) -> str:
    """Anchored regular expression for one excluded path ('/exact', '/prefix/*' or '*.ext')."""
    if p.startswith("*."):
        return f"\\.{re.escape(p[2:])}$"
    if p.endswith("*"):
        return "^" + re.escape(p[:-1])
    return "^" + re.escape(p) + "$"


def apache(bl: Blocklist, cfg: Config) -> str:
    """mod_rewrite rules for Apache 2.4: a <VirtualHost>, the server config or the top of an .htaccess.

    Apache cannot drop a connection from configuration, so the answer is 403 Forbidden. Conditions are ANDed unless
    flagged [OR], and [OR] binds tighter: (not excluded path) AND (robot OR network OR network...).
    """
    lines = _header(
        "#",
        bl,
        "Include it in your <VirtualHost> (Include /etc/apache2/n-antibot.conf) or paste it at the top of .htaccess",
    )
    lines.append("RewriteEngine On")
    lines += [f'RewriteCond %{{REQUEST_URI}} "!{_regex_path(x)}"' for x in cfg.exclude_paths]
    ors: list[str] = []
    if bl.agents:
        ors.append(f'RewriteCond %{{HTTP_USER_AGENT}} "{_alt(bl.agents)}" [NC')
    ranges = bl.v4 + bl.v6
    for i in range(0, len(ranges), 8):
        ors.append('RewriteCond expr "' + " || ".join(f"-R '{r}'" for r in ranges[i : i + 8]) + '" [')
    for i, cond in enumerate(ors):
        last = i == len(ors) - 1
        if cond.endswith("[NC"):
            lines.append(cond + ("]" if last else ",OR]"))
        else:
            lines.append(cond[:-2] if last else cond + "OR]")
    if ors:
        lines.append("RewriteRule ^ - [F,L]")
    else:
        lines = [x for x in lines if not x.startswith("RewriteCond")]
    ads = [*bl.ads_v4, *bl.ads_v6]
    if ads:
        # Data-center networks are only cut when the request is a paid ad click (it carries a click identifier).
        lines += [f'RewriteCond %{{REQUEST_URI}} "!{_regex_path(x)}"' for x in cfg.exclude_paths]
        lines.append(f'RewriteCond %{{QUERY_STRING}} "{AD_CLICK_RE}"')
        chunks = [ads[i : i + 8] for i in range(0, len(ads), 8)]
        for i, chunk in enumerate(chunks):
            cond = 'RewriteCond expr "' + " || ".join(f"-R '{r}'" for r in chunk) + '"'
            lines.append(cond if i == len(chunks) - 1 else cond + " [OR]")
        lines.append("RewriteRule ^ - [F,L]")
    lines.append("")
    return "\n".join(lines)


def nftables(bl: Blocklist, cfg: Config) -> str:
    """Ruleset for `nft -f`: drops packets from the blocked networks before they reach any web server.

    Networks only: a firewall does not see the User-Agent or the path, so robots and excluded paths do not apply.
    The prerouting hook also covers ports published by Docker. Loading the file again replaces the table atomically.
    """
    t = cfg.nftables_table
    ports = ", ".join(str(p) for p in cfg.nftables_ports)
    lines = _header(
        "#",
        replace(bl, agents=()),
        f"Load it with: nft -f /etc/nftables.d/n-antibot.nft, remove it with: nft delete table inet {t}",
    )
    lines += [f"add table inet {t}", f"delete table inet {t}", f"table inet {t} {{"]
    rules: list[str] = []
    for name, kind, family, items in (("v4", "ipv4_addr", "ip", bl.v4), ("v6", "ipv6_addr", "ip6", bl.v6)):
        if not items:
            continue
        lines += [f"\tset {name} {{", f"\t\ttype {kind}", "\t\tflags interval", "\t\telements = {"]
        lines += [f"\t\t\t{', '.join(items[i : i + 6])}," for i in range(0, len(items), 6)]
        lines += ["\t\t}", "\t}"]
        rules.append(f"\t\ttcp dport {{ {ports} }} {family} saddr @{name} drop")
        rules.append(f"\t\tudp dport {{ {ports} }} {family} saddr @{name} drop")
    lines += [
        "\tchain prerouting {",
        "\t\ttype filter hook prerouting priority -150; policy accept;",
        *rules,
        "\t}",
        "}",
        "",
    ]
    return "\n".join(lines)


def _cf_path(p: str) -> str:
    field = "http.request.uri.path"
    if p.startswith("*."):
        return f'ends_with({field}, "{p[1:]}")'
    if p.endswith("*"):
        return f'starts_with({field}, "{p[:-1]}")'
    return f'{field} eq "{p}"'


def cloudflare(bl: Blocklist, cfg: Config) -> str:
    """Expression for a Cloudflare WAF custom rule (action: Block). The expression is the last line.

    Cloudflare knows the ASN of every visitor, so networks are matched by ASN instead of by expanded ranges.
    """
    block: list[str] = []
    if bl.asns:
        block.append("ip.src.asnum in {" + " ".join(a[2:] for a in bl.asns) + "}")
    if bl.manual_block:
        block.append("ip.src in {" + " ".join(bl.manual_block) + "}")
    block += [f'lower(http.user_agent) contains "{a.lower()}"' for a in bl.agents]
    if bl.ads_asns:
        # Data-center networks are only cut when the request is a paid ad click (it carries a click identifier).
        click = " or ".join(f'http.request.uri.query contains "{name}="' for name in AD_CLICK_PARAMS)
        block.append("(ip.src.asnum in {" + " ".join(a[2:] for a in bl.ads_asns) + "} and (" + click + "))")
    expr = "(" + " or ".join(block) + ")"
    if bl.manual_allow:
        expr += " and not ip.src in {" + " ".join(bl.manual_allow) + "}"
    for p in cfg.exclude_paths:
        expr += f" and not {_cf_path(p)}"
    lines = _header(
        "#", bl, "Cloudflare > Security > WAF > Custom rules > Edit expression: paste the LAST line, action Block"
    )
    return "\n".join([*lines, "", expr, ""])


def as_json(bl: Blocklist, cfg: Config) -> str:
    """Plain data, for a WAF, a CDN rule, fail2ban or your own middleware."""
    return (
        json.dumps(
            {
                "generator": f"n-antibot {__version__}",
                "generated_on": bl.generated_on,
                "asns": list(bl.asns),
                "ipv4": bl.v4,
                "ipv6": bl.v6,
                "user_agents": list(bl.agents),
                "user_agent_regex": "(?i)" + _alt(bl.agents) if bl.agents else None,
                "exclude_paths": list(cfg.exclude_paths),
                "ad_clicks": {
                    "cut": bool(bl.ads_v4 or bl.ads_v6),
                    "params": list(AD_CLICK_PARAMS),
                    "asns": list(bl.ads_asns),
                    "ipv4": list(bl.ads_v4),
                    "ipv6": list(bl.ads_v6),
                },
            },
            indent=2,
        )
        + "\n"
    )


def _alt(agents: tuple[str, ...]) -> str:
    return "(" + "|".join(agents) + ")"


RENDERERS = {
    "caddy": caddy,
    "nginx": nginx,
    "apache": apache,
    "nftables": nftables,
    "cloudflare": cloudflare,
    "json": as_json,
}


def render(bl: Blocklist, cfg: Config) -> str:
    return RENDERERS[cfg.format](bl, cfg)


def strip_header(text: str) -> str:
    """Content without the dated header, to compare two generations."""
    lines = text.split("\n")
    if lines and lines[0].lstrip().startswith("{"):  # JSON
        try:
            d = json.loads(text)
            d.pop("generated_on", None)
            d.pop("generator", None)
            return json.dumps(d, sort_keys=True)
        except ValueError:
            return text
    return "\n".join(lines[HEADER_LINES:])
