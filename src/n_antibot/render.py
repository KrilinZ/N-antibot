"""Renderers: turn the final lists into a Caddy snippet, an nginx include or JSON."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from . import __version__
from .config import Config

HEADER_LINES = 3  # comment lines that carry the date; ignored by `n-antibot check`


@dataclass(frozen=True)
class Blocklist:
    v4: list[str]
    v6: list[str]
    agents: tuple[str, ...]
    asns: tuple[str, ...]
    generated_on: str


def _header(c: str, bl: Blocklist, where: str) -> list[str]:
    return [
        f"{c} Generated by n-antibot {__version__} on {bl.generated_on}. Do not edit by hand: regenerate it.",
        f"{c} {where}",
        f"{c} Networks: {', '.join(bl.asns) or 'none'} · {len(bl.v4)} IPv4 and {len(bl.v6)} IPv6 ranges · "
        f"{len(bl.agents)} robots.",
    ]


def caddy(bl: Blocklist, cfg: Config) -> str:
    """Snippet to `import` as the FIRST line inside a site block.

    Caddy sorts directives: `rewrite` runs before every `handle`, and a `handle` with an exact path wins over
    `handle /prefix/*` and the catch-all `handle`. A named matcher inside `handle @x` would be sorted AFTER path
    handles, so the block would not reach every route. Hence: rewrite to a private path, then abort there.
    """
    p, dest = cfg.caddy_prefix, cfg.caddy_block_path
    excl = " ".join(cfg.exclude_paths)
    lines = _header("#", bl, "Import it as the first line of your site block: import /etc/caddy/n-antibot.caddy")
    ranges = bl.v4 + bl.v6
    if ranges:
        lines.append(f"@{p}Net {{")
        if excl:
            lines.append(f"\tnot path {excl}")
        for i in range(0, len(ranges), 8):
            lines.append(f"\t{cfg.caddy_ip_matcher} " + " ".join(ranges[i : i + 8]))
        lines.append("}")
    if bl.agents:
        lines.append(f"@{p}Agent {{")
        if excl:
            lines.append(f"\tnot path {excl}")
        lines.append(f'\theader_regexp {p}Ua User-Agent "(?i){_alt(bl.agents)}"')
        lines.append("}")
    if ranges:
        lines.append(f"rewrite @{p}Net {dest}")
    if bl.agents:
        lines.append(f"rewrite @{p}Agent {dest}")
    lines += [f"handle {dest} {{", "\tabort", "}", ""]
    return "\n".join(lines)


def _nginx_path(p: str) -> str:
    if p.startswith("*."):
        return f"~\\.{re.escape(p[2:])}$"
    if p.endswith("*"):
        return "~^" + re.escape(p[:-1])
    return p  # exact match


def nginx(bl: Blocklist, cfg: Config) -> str:
    """Include for the `http {}` context. It defines $<prefix>_block; add `if ($<prefix>_block) { return 444; }`
    to each server. 444 is nginx's "close the connection without answering", the same as Caddy's abort."""
    p = cfg.nginx_prefix
    lines = _header("#", bl, f"include it inside http {{ }} and add to each server: if (${p}_block) {{ return 444; }}")
    lines += [f"geo ${p}_net {{", "\tdefault 0;"]
    lines += [f"\t{r} 1;" for r in bl.v4 + bl.v6]
    lines += ["}", f"map $http_user_agent ${p}_agent {{", "\tdefault 0;"]
    if bl.agents:
        lines.append(f'\t"~*{_alt(bl.agents)}" 1;')
    lines += ["}", f"map $uri ${p}_excluded {{", "\tdefault 0;"]
    lines += [f'\t"{_nginx_path(x)}" 1;' for x in cfg.exclude_paths]
    lines += [
        "}",
        f'map "${p}_net${p}_agent${p}_excluded" ${p}_block {{',
        "\tdefault 0;",
        '\t"100" 1;',
        '\t"010" 1;',
        '\t"110" 1;',
        "}",
        "",
    ]
    return "\n".join(lines)


def as_json(bl: Blocklist, cfg: Config) -> str:
    """Plain data, for a WAF, a CDN rule, fail2ban or your own middleware."""
    return (
        json.dumps(
            {
                "generator": f"n-antibot {__version__}",
                "generated_on": bl.generated_on,
                "asns": list(bl.asns),
                "ipv4": bl.v4,
                "ipv6": bl.v6,
                "user_agents": list(bl.agents),
                "user_agent_regex": "(?i)" + _alt(bl.agents) if bl.agents else None,
                "exclude_paths": list(cfg.exclude_paths),
            },
            indent=2,
        )
        + "\n"
    )


def _alt(agents: tuple[str, ...]) -> str:
    return "(" + "|".join(agents) + ")"


RENDERERS = {"caddy": caddy, "nginx": nginx, "json": as_json}


def render(bl: Blocklist, cfg: Config) -> str:
    return RENDERERS[cfg.format](bl, cfg)


def strip_header(text: str) -> str:
    """Content without the dated header, to compare two generations."""
    lines = text.split("\n")
    if lines and lines[0].lstrip().startswith("{"):  # JSON
        try:
            d = json.loads(text)
            d.pop("generated_on", None)
            d.pop("generator", None)
            return json.dumps(d, sort_keys=True)
        except ValueError:
            return text
    return "\n".join(lines[HEADER_LINES:])
